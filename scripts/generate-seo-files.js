// Main generation function
export function generateAllSEOFiles() {
  const sitemapXml = generateSitemap();
  const robotsTxt = generateRobotsTxt();

  // Ensure output directory exists
  try {
    mkdirSync(OUT_DIR, { recursive: true });
  } catch {}

  // Write files
  writeFileSync(join(OUT_DIR, 'sitemap.xml'), sitemapXml);
  writeFileSync(join(OUT_DIR, 'robots.txt'), robotsTxt);
  console.log('✓ sitemap.xml generated');
  console.log('✓ robots.txt generated');

  return {
    sitemapPath: join(OUT_DIR, 'sitemap.xml'),
    robotsPath: join(OUT_DIR, 'robots.txt'),
    schemaGenerators: Object.keys(schemas),
  };
}

// Execute if run directly
if (process.argv[1]?.endsWith('generate-seo-files.js')) {
  const result = generateAllSEOFiles();
  console.log('SEO generation complete:', result);
}

export default { generateAllSEOFiles, generateSitemap, generateRobotsTxt, generateSchemaJsonLd };
