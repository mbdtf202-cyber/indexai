/**
 * SEO Files Generator (T5.10 Round 1)
 *
 * Generates sitemap.xml, robots.txt, and canonical URLs for all pages
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

import { BASE_URL as SITE_BASE } from '../lib/config.js';

const BASE_URL = process.env.BASE_URL || SITE_BASE;
const OUT_DIR = 'dist';

// Generate sitemap.xml
export function generateSitemap() {
  const pages = [
    { url: '/', priority: 1.0, changefreq: 'daily', lastmod: new Date().toISOString() },
    { url: '/models', priority: 0.9, changefreq: 'hourly', lastmod: new Date().toISOString() },
    { url: '/benchmarks', priority: 0.8, changefreq: 'hourly', lastmod: new Date().toISOString() },
    {
      url: '/subscriptions',
      priority: 0.7,
      changefreq: 'weekly',
      lastmod: new Date().toISOString(),
    },
    { url: '/free', priority: 0.7, changefreq: 'daily', lastmod: new Date().toISOString() },
    { url: '/relays', priority: 0.6, changefreq: 'daily', lastmod: new Date().toISOString() },
    { url: '/events', priority: 0.5, changefreq: 'daily', lastmod: new Date().toISOString() },
    { url: '/tools', priority: 0.5, changefreq: 'weekly', lastmod: new Date().toISOString() },
    { url: '/vendors', priority: 0.5, changefreq: 'daily', lastmod: new Date().toISOString() },
    { url: '/signals', priority: 0.4, changefreq: 'daily', lastmod: new Date().toISOString() },
    {
      url: '/methodology',
      priority: 0.3,
      changefreq: 'monthly',
      lastmod: new Date().toISOString(),
    },
  ];

  let sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n`;
  sitemap += `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;

  for (const page of pages) {
    sitemap += `  <url>\n`;
    sitemap += `    <loc>${BASE_URL}${page.url}</loc>\n`;
    sitemap += `    <lastmod>${page.lastmod}</lastmod>\n`;
    sitemap += `    <changefreq>${page.changefreq}</changefreq>\n`;
    sitemap += `    <priority>${page.priority}</priority>\n`;
    sitemap += `  </url>\n`;
  }

  sitemap += `</urlset>`;
  return sitemap;
}

// Generate robots.txt
export function generateRobotsTxt() {
  return `# robots.txt for IndexAI
# Generated by generate-seo-files.js

User-agent: *
Allow: /

Disallow: /api/
Disallow: /*?*

# Sitemap location
Sitemap: ${BASE_URL}/sitemap.xml

# Crawl delay recommendation
Crawl-delay: 1
`;
}

