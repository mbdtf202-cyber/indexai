/**
 * GitHub Issue 集成（T4.2 · T3.1d）
 *
 * 纯函数接口：根据告警决策开 / 追加 / 关闭 issue。
 *
 * 网络只走 `lib/http.js`（R2a · INV-14）：告警路径同样需要超时、重试与记账，
 * 直接调 `fetch` 会绕开这三件事，也会在断网时挂住 CI。
 */

import { httpGet } from '../../lib/http.js';
import { nowISO } from '../../lib/clock.js';

/**
 * 调一次 GitHub API 并返回结构化响应。
 * @param {{url: string, method: string, headers: object, payload?: object, label: string}} req
 */
async function call({ url, method, headers, payload, label }) {
  const res = await httpGet(url, {
    method,
    headers: { ...headers, 'Content-Type': 'application/json' },
    body: payload === undefined ? undefined : JSON.stringify(payload),
    label,
    tries: 2,
  });
  const text = await res.text();
  return { ok: res.ok, status: res.status, statusText: res.statusText, text };
}

/** 解析响应体；空体返回 null 而不是抛。 */
function parseBody(text) {
  if (!text) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

/** 找出带指定标签的已开 issue。 */
async function findOpenIssue({ baseUrl, owner, repo, label, headers }) {
  const params = new URLSearchParams({ state: 'open', labels: label, per_page: '100' });
  const res = await call({
    url: `${baseUrl}/${owner}/${repo}/issues?${params}`,
    method: 'GET',
    headers,
    label: `github/${owner}/${repo}/issues`,
  });
  if (!res.ok) throw new Error(`GitHub search error: ${res.status}`);
  const issues = parseBody(res.text) || [];
  return issues.find((i) => i.labels?.some((l) => (l.name || l) === label)) || null;
}

/**
 * 根据告警决策操作 GitHub issue。
 * @param {object} options
 * @param {string} options.owner
 * @param {string} options.repo
 * @param {string} options.token
 * @param {object} options.alertInfo
 * @param {'open'|'append'|'close'} options.action
 * @returns {Promise<{success: boolean, action: string, issue_number?: number, reason?: string}>}
 */
export async function handleAlertDecision({ owner, repo, token, alertInfo, action }) {
  const baseUrl = 'https://api.github.com/repos';
  const headers = {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
  };

  const label = `layer:${alertInfo.layer}`;

  switch (action) {
    case 'open': {
      const res = await call({
        url: `${baseUrl}/${owner}/${repo}/issues`,
        method: 'POST',
        headers,
        label: `github/${owner}/${repo}`,
        payload: {
          title: `[${alertInfo.layer}] ${alertInfo.reason}`,
          labels: [label],
          body: [
            '### Alert Detected',
            '',
            `**Layer**: ${alertInfo.layer}`,
            `**Reason**: ${alertInfo.reason}`,
            `**First Bad State**: ${alertInfo.firstBad ? new Date(alertInfo.firstBad).toISOString() : 'N/A'}`,
            '',
            'Generated by IndexAI alert system.',
          ].join('\n'),
        },
      });
      if (!res.ok) throw new Error(`GitHub API error: ${res.status} ${res.statusText}`);
      const data = parseBody(res.text);
      return { success: true, action: 'open', issue_number: data?.number };
    }

    case 'append': {
      const existing = await findOpenIssue({ baseUrl, owner, repo, label, headers });
      if (!existing) {
        // 没有可追加的 issue 就新开一条：调用方不该为了这个分支写两遍逻辑
        return handleAlertDecision({ owner, repo, token, alertInfo, action: 'open' });
      }
      const res = await call({
        url: existing.comments_url,
        method: 'POST',
        headers,
        label: `github/${owner}/${repo}/comments`,
        payload: {
          body: [
            '### Alert Continued',
            '',
            `**Timestamp**: ${nowISO()}`,
            `**Reason**: ${alertInfo.reason}`,
            '',
            `Issue opened at ${new Date(existing.created_at).toISOString()}.`,
          ].join('\n'),
        },
      });
      if (!res.ok) throw new Error(`Comment error: ${res.status}`);
      return { success: true, action: 'append', issue_number: existing.number };
    }

    case 'close': {
      const existing = await findOpenIssue({ baseUrl, owner, repo, label, headers });
      if (!existing) {
        return { success: false, action: 'none', reason: '没有可关闭的 open issue' };
      }
      const res = await call({
        url: existing.url,
        method: 'PATCH',
        headers,
        label: `github/${owner}/issues/${existing.number}`,
        payload: {
          state: 'closed',
          body: [
            '### Alert Resolved',
            '',
            `Recovery detected at ${nowISO()}. Closing this issue.`,
          ].join('\n'),
        },
      });
      if (!res.ok) throw new Error(`Close error: ${res.status}`);
      return { success: true, action: 'close', issue_number: existing.number };
    }

    default:
      return { success: false, action: 'none', reason: '未知动作' };
  }
}

export default { handleAlertDecision };
