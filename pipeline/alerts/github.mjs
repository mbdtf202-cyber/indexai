/**
 * GitHub Issue Integration (T4.2 Round 2)
 *
 * 纯函数接口：根据告警决策调用 GitHub API 开/追加/关闭 issue
 */

/**
 * Create or append GitHub Issue based on alert decision
 * @param {object} options - Required parameters
 * @param {string} options.owner - GitHub repo owner
 * @param {string} options.repo - GitHub repo name
 * @param {string} options.token - GitHub token (from env)
 * @param {object} alertInfo - Alert metadata
 * @param {string} alertInfo.layer - Layer ID
 * @param {string} alertInfo.firstBad - First bad state timestamp
 * @param {string} alertInfo.reason - Reason string
 * @param {'open'|'append'|'close'} options.action - Decision from detectAlertDecision
 * @returns {Promise<object>} Result with issue number/status
 */
export async function handleAlertDecision({ owner, repo, token, alertInfo, action }) {
  const baseUrl = 'https://api.github.com/repos';
  const headers = {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
  };

  const label = `layer:${alertInfo.layer}`;
  const title = `[${alertInfo.layer}] ${alertInfo.reason.split(' ')[0]}`; // Short title

  switch (action) {
    case 'open': {
      // Open new issue
      const response = await fetch(`${baseUrl}/${owner}/${repo}/issues`, {
        method: 'POST',
        headers,
        body: JSON.stringify({
          title: `${title}: ${alertInfo.reason}`,
          labels: [label],
          body: `### Alert Detected\n\n**Layer**: ${alertInfo.layer}\n**Reason**: ${alertInfo.reason}\n**First Bad State**: ${alertInfo.firstBad ? new Date(alertInfo.firstBad).toISOString() : 'N/A'}\n\nGenerated by IndexAI alert system.`,
        }),
      });

      if (!response.ok) {
        throw new Error(`GitHub API error: ${response.status} ${response.statusText}`);
      }

      const data = await response.json();
      return { success: true, action: 'open', issue_number: data.number };
    }

    case 'append': {
      // Find existing issue with layer label and append comment
      const searchParams = new URLSearchParams({
        state: 'open',
        labels: label,
        per_page: 100,
      });

      const listResponse = await fetch(`${baseUrl}/${owner}/${repo}/issues?${searchParams}`, {
        headers,
      });
      if (!listResponse.ok) {
        throw new Error(`GitHub search error: ${listResponse.status}`);
      }

      const issues = await listResponse.json();
      const existingIssue = issues.find((i) => i.labels.some((l) => l.name === label));

      if (existingIssue) {
        // Append comment to existing issue
        const commentResponse = await fetch(existingIssue.comments_url, {
          method: 'POST',
          headers,
          body: JSON.stringify({
            body: `### Alert Continued\n\n**Timestamp**: ${new Date().toISOString()}\n**Status**: ${alertInfo.status || 'continuing'}\n\nPrevious alert was opened on ${new Date(existingIssue.created_at).toISOString()}.`,
          }),
        });

        if (!commentResponse.ok) {
          throw new Error(`Comment error: ${commentResponse.status}`);
        }

        return { success: true, action: 'append', issue_number: existingIssue.number };
      } else {
        // Fallback to open if no existing issue found
        const newIssue = await handleAlertDecision({
          owner,
          repo,
          token,
          alertInfo,
          action: 'open',
        });
        return newIssue;
      }
    }

    case 'close': {
      // Close matching issue
      const searchParams = new URLSearchParams({
        state: 'open',
        labels: label,
        per_page: 100,
      });

      const listResponse = await fetch(`${baseUrl}/${owner}/${repo}/issues?${searchParams}`, {
        headers,
      });
      if (!listResponse.ok) {
        throw new Error(`GitHub search error: ${listResponse.status}`);
      }

      const issues = await listResponse.json();
      const issueToClose = issues.find((i) => i.labels.some((l) => l.name === label));

      if (issueToClose) {
        const closeResponse = await fetch(issueToClose.url, {
          method: 'PATCH',
          headers,
          body: JSON.stringify({
            state: 'closed',
            body: `### Alert Resolved\n\nRecovery detected at ${new Date().toISOString()}. This issue is now closed.\n\nSee https://github.com/${owner}/${repo}/actions/runs/\${GITHUB_RUN_ID} for run details.`,
          }),
        });

        if (!closeResponse.ok) {
          throw new Error(`Close error: ${closeResponse.status}`);
        }

        return { success: true, action: 'close', issue_number: issueToClose.number };
      }

      return { success: false, action: 'none', reason: 'No matching open issue found' };
    }

    default:
      return { success: false, action: 'none', reason: 'No action needed' };
  }
}

// CLI usage
if (process.argv[1]?.endsWith('github.mjs')) {
  console.log('Usage: node github.mjs --action=open --layer=test --reason="consecutive failures"');
  process.exit(1);
}

export default { handleAlertDecision };
